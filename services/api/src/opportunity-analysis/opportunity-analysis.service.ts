import {
  Injectable,
  NotFoundException,
  ForbiddenException,
  Logger,
} from '@nestjs/common';
import { HttpService } from '@nestjs/axios';
import { firstValueFrom } from 'rxjs';
import { UserRole } from '../common/types';
import { arrToStr, strToArr } from '../common/db-helpers';
import { PrismaService } from '../prisma/prisma.service';

@Injectable()
export class OpportunityAnalysisService {
  private readonly logger = new Logger(OpportunityAnalysisService.name);

  constructor(
    private prisma: PrismaService,
    private httpService: HttpService,
  ) { }

  async requestAnalysis(opportunityId: string, userId: string, role: UserRole) {
    const opp = await this.prisma.opportunity.findUnique({ where: { id: opportunityId } });
    if (!opp) throw new NotFoundException('Opportunity not found.');

    const isOwner = opp.ownerId === userId;
    const isAdmin = role === UserRole.ADMIN;
    if (!isOwner && !isAdmin) {
      throw new ForbiddenException('You do not have permission to request analysis for this opportunity.');
    }

    // Create analysis record in PENDING state
    const analysis = await this.prisma.opportunityAnalysis.create({
      data: {
        opportunityId,
        inputVersion: opp.updatedAt.toISOString(),
        status: 'PENDING',
      },
    });

    // Trigger async analysis (fire and forget)
    this.runAnalysis(analysis.id, opp).catch((err) =>
      this.logger.error(`Analysis ${analysis.id} failed: ${err.message}`),
    );

    return { analysisId: analysis.id, status: 'PENDING', message: 'Analysis requested. Results will be available shortly.' };
  }

  async getLatestAnalysis(opportunityId: string, userId: string, role: UserRole) {
    const opp = await this.prisma.opportunity.findUnique({ where: { id: opportunityId } });
    if (!opp) throw new NotFoundException('Opportunity not found.');

    const isOwner = opp.ownerId === userId;
    const isAdmin = role === UserRole.ADMIN;
    const isPublished = opp.status === 'PUBLISHED';

    if (!isOwner && !isAdmin && !isPublished) {
      throw new ForbiddenException('Access denied.');
    }

    const analysis = await this.prisma.opportunityAnalysis.findFirst({
      where: { opportunityId, status: 'COMPLETED' },
      orderBy: { createdAt: 'desc' },
    });

    if (!analysis) {
      return {
        status: 'NO_ANALYSIS',
        message: 'No completed analysis available yet.',
        disclaimer: 'AI-generated content. Information has not been independently verified.',
      };
    }

    return {
      ...analysis,
      categories: strToArr(analysis.categories),
      missingInformation: strToArr(analysis.missingInformation),
      suggestedQuestions: strToArr(analysis.suggestedQuestions),
      disclaimer: analysis.disclaimer || 'AI-generated assistance. Information has not been independently verified.',
      note: 'This summary was generated by AI based on the submitted information. It does not constitute verification, investment advice, or a guarantee of any outcome.',
    };
  }

  private async runAnalysis(analysisId: string, opp: any) {
    await this.prisma.opportunityAnalysis.update({
      where: { id: analysisId },
      data: { status: 'PROCESSING' },
    });

    try {
      const aiServiceUrl = process.env.AI_SERVICE_URL || 'http://localhost:8000';
      const apiKey = process.env.AI_SERVICE_API_KEY || '';

      const payload = {
        opportunity_id: opp.id,
        title: opp.title,
        type: opp.type,
        description: opp.description,
        sector: opp.sector,
        location: opp.location,
        stage: opp.stage,
        problem: opp.problem,
        solution: opp.solution,
        goals: opp.goals,
      };

      const response = await firstValueFrom(
        this.httpService.post(`${aiServiceUrl}/internal/v1/opportunity-analysis`, payload, {
          headers: { 'X-API-Key': apiKey },
          timeout: 60000,
        }),
      );

      const result = response.data;

      await this.prisma.opportunityAnalysis.update({
        where: { id: analysisId },
        data: {
          summary: result.summary,
          categories: arrToStr(result.categories || []),
          missingInformation: arrToStr(result.missing_information || []),
          suggestedQuestions: arrToStr(result.suggested_questions || []),
          disclaimer: result.disclaimer,
          modelIdentifier: result.model_identifier,
          status: 'COMPLETED',
        },
      });

      this.logger.log(`Analysis ${analysisId} completed successfully.`);
    } catch (error) {
      this.logger.error(`Analysis ${analysisId} failed: ${error.message}`);
      await this.prisma.opportunityAnalysis.update({
        where: { id: analysisId },
        data: {
          status: 'FAILED',
          errorMessage: error.message,
        },
      });
    }
  }
}
